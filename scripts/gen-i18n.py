#!/usr/bin/env python3
# 中文说明：多语言（i18n）辅助脚本
#
# 用途：
#   1. 生成模式：python3 scripts/gen-i18n.py
#      根据 i18n/zh.txt（中文原文）和 i18n/en.txt（英文译文）重新生成
#      entry/src/main/ets/common/LangEn.ets（英文翻译表，请勿手改）。
#   2. 检查模式：python3 scripts/gen-i18n.py --check
#      扫描所有 .ets 源码中 t(...) / tf(...) 的单引号字面量参数，列出 zh.txt 中没有的字符串
#      （即缺少英文翻译），有缺失时退出码为 1，可用于 CI。
#
# 约定：zh.txt 与 en.txt 逐行对齐（en.txt 第 N 行是 zh.txt 第 N 行的翻译）；
# 每行按源码中字面量的原样书写（例如 \n 等转义保持原样）；
# 通过变量传给翻译函数的字符串（分区标题、预设名等）也需要手工写进 zh.txt。
"""i18n helper.

  gen-i18n.py           regenerate entry/src/main/ets/common/LangEn.ets from i18n/zh.txt + i18n/en.txt
  gen-i18n.py --check   list t()/tf() strings in the sources that have no English entry (exit 1 if any)

i18n/zh.txt and i18n/en.txt are line-aligned: line N of en.txt translates line N of zh.txt. Lines are written
exactly as the string literal appears in the .ets source (escapes such as \\n kept as typed).
Strings passed to t() through a variable (section titles, presets, …) are listed in zh.txt too.
"""
import os, re, sys
# 项目根目录（scripts/ 的上一级）与 ArkTS 源码目录
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'entry/src/main/ets')


def read(p):
    """读取项目根目录下的文本文件并按行拆分；去掉文件末尾换行产生的最后一个空行。"""
    ls = open(os.path.join(ROOT, p), encoding='utf-8').read().split('\n')
    if ls and ls[-1] == '':
        ls.pop()
    return ls


# 读取中英文对照表；两者必须逐行对齐，行数不同说明有遗漏，直接报错退出
zh, en = read('i18n/zh.txt'), read('i18n/en.txt')
if len(zh) != len(en):
    sys.exit('zh.txt has %d lines, en.txt has %d' % (len(zh), len(en)))

# 检查模式：只扫描、不生成文件
if '--check' in sys.argv:
    # 匹配 t('…') / tf('…') 的第一个单引号字面量参数（支持 \x 形式的转义，不跨行）
    pat = re.compile(r"\bt[f]?\(\s*'((?:[^'\\\n]|\\.)*)'")
    known = set(zh)
    missing = []
    # 遍历所有 .ets 文件，收集不在 zh.txt 中的字符串（去重并保持首次出现顺序）
    for root, _, fs in os.walk(SRC):
        for f in fs:
            if f.endswith('.ets'):
                for m in pat.finditer(open(os.path.join(root, f), encoding='utf-8').read()):
                    if m.group(1) not in known and m.group(1) not in missing:
                        missing.append(m.group(1))
    for m in missing:
        print('missing:', m)
    print('%d strings, %d missing' % (len(zh), len(missing)))
    sys.exit(1 if missing else 0)


def q(s):
    """把文本包装成 ArkTS 单引号字符串字面量：已包含转义过的单引号时原样包装，否则转义其中的单引号。"""
    return "'" + s.replace("'", "\\'") + "'" if "\\'" not in s else "'" + s + "'"


# 生成模式：输出 LangEn.ets，EN_PAIRS 为“中文, 英文, 中文, 英文, …”的扁平数组
out = ['/** English UI strings. Generated by scripts/gen-i18n.py from i18n/zh.txt + i18n/en.txt; do not edit. */',
       '', '/** Flat list: Chinese source, English, Chinese source, English, … */',
       'export const EN_PAIRS: string[] = [']
rows = []
for a, b in zip(zh, en):
    rows.append('  %s, %s' % (q(a), q(b)))
out.append(',\n'.join(rows))
out.append('];')
out.append('')
# 写入生成文件（UTF-8）
open(os.path.join(SRC, 'common/LangEn.ets'), 'w', encoding='utf-8').write('\n'.join(out))
print('LangEn.ets: %d strings' % len(zh))
