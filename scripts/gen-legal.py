#!/usr/bin/env python3
"""Generates entry/src/main/ets/common/LegalText.ets from docs/privacy*.md, docs/terms*.md and docs/licenses/*.txt.
Run after editing any of them (the same markdown is published on the website). Do not edit the output by hand."""
import json, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')


def lines(p):
    ls = open(os.path.join(root, p), encoding='utf-8').read().split('\n')
    while ls and ls[-1] == '':
        ls.pop()
    # the in-app renderer has no inline markup: drop **bold** markers (the website keeps them)
    return [l.replace('**', '') for l in ls]


out = ['/** Legal texts. Generated by scripts/gen-legal.py from docs/; do not edit. */', '']
for name, p in [('PRIVACY_LINES', 'docs/privacy.md'), ('AGREEMENT_LINES', 'docs/terms.md'),
                ('PRIVACY_LINES_EN', 'docs/privacy.en.md'), ('AGREEMENT_LINES_EN', 'docs/terms.en.md')]:
    out.append('export const %s: string[] = [' % name)
    out.append(',\n'.join('  ' + json.dumps(l, ensure_ascii=False) for l in lines(p)))
    out.append('];')
    out.append('')

# name, version, purpose (zh source; translated via i18n), license id, file — generated from the core's module
# graph into docs/licenses/index.json (see README: 开源许可)
LICS = json.load(open(os.path.join(root, 'docs/licenses/index.json'), encoding='utf-8'))
out.append('export class LicenseInfo {')
out.append('  name: string;\n  version: string;\n  purpose: string;\n  license: string;\n  text: string;\n')
out.append('  constructor(name: string, version: string, purpose: string, license: string, text: string) {')
out.append('    this.name = name;\n    this.version = version;\n    this.purpose = purpose;\n    this.license = license;\n    this.text = text;\n  }\n}\n')
out.append('export const LICENSES: LicenseInfo[] = [')
rows = []
for n, v, pu, li, f in LICS:  # noqa
    txt = open(os.path.join(root, 'docs/licenses', f), encoding='utf-8').read().strip()
    rows.append('  new LicenseInfo(%s, %s, %s, %s,\n    %s)' % tuple(json.dumps(x, ensure_ascii=False) for x in (n, v, pu, li, txt)))
out.append(',\n'.join(rows))
out.append('];')
out.append('')
open(os.path.join(root, 'entry/src/main/ets/common/LegalText.ets'), 'w', encoding='utf-8').write('\n'.join(out))
print('ok')
